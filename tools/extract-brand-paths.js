// Extract the shipped DeepSeek Harness brand geometry from the primitives bundle
// so a prototype can render the *real* wordmark instead of an approximation.
//
// The wordmark is one <path> per glyph, every one of them `currentColor`, which
// is exactly why per-word colouring is possible at all — but the paths are not
// in left-to-right order, so the prototype groups them by bounding box.
//
// usage: node tools/extract-brand-paths.js <primitives-index.js> <out.js>
'use strict';

const fs = require('fs');

const [, , source, target] = process.argv;
const text = fs.readFileSync(source, 'utf8');

function region(name) {
  const start = text.indexOf(`//#region lib/types/${name}.js`);
  if (start === -1) throw new Error(`region ${name} not found`);
  const end = text.indexOf('//#endregion', start);
  return text.slice(start, end === -1 ? undefined : end);
}

const fishRegion = region('FishLogo');
const fish = /FISH_LOGO_PATH = "([^"]+)"/.exec(fishRegion);
if (!fish) throw new Error('FISH_LOGO_PATH not found');

const wordmarkRegion = region('BrandWordmark');
const glyphs = [...wordmarkRegion.matchAll(/\bd:\s*"([^"]+)"/g)].map((m) => m[1]);
if (glyphs.length === 0) throw new Error('no glyph paths found in the wordmark region');

const payload = {
  fish: fish[1],
  glyphs,
  source: 'dsh-client-ui-primitives lib/types/BrandWordmark.js',
};

fs.writeFileSync(
  target,
  '// Generated by tools/extract-brand-paths.js — do not edit.\n' +
    '// Real DeepSeek Harness brand geometry, extracted from the shipped bundle.\n' +
    'window.BRAND_PATHS = ' +
    JSON.stringify(payload, null, 2) +
    ';\n'
);

console.log(`fish path: ${fish[1].length} chars | glyphs: ${glyphs.length}`);
